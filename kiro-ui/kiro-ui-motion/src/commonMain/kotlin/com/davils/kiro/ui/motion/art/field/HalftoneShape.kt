package com.davils.kiro.ui.motion.art.field

/**
 * The shape of a dot of a [HalftoneArt].
 *
 * @since 1.0.0
 */
public enum class HalftoneShape {
    /**
     * A circle.
     *
     * @since 1.0.0
     */
    Circle,

    /**
     * A square, turned with the grid.
     *
     * @since 1.0.0
     */
    Square,

    /**
     * A square standing on its corner.
     *
     * @since 1.0.0
     */
    Diamond,
}
